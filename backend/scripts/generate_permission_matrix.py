"""Write docs/security/PERMISSION_MATRIX.md from the code (roles x permissions) and the golden endpoint matrix.

    python scripts/generate_permission_matrix.py
"""
import json
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND))

from app.core.permissions import ALL_PERMISSIONS, ROLE_PERMISSIONS  # noqa: E402

ROLES = ["ADMIN", "DEVELOPER", "COMMANDER", "OPERATOR", "RESCUE_OFFICER", "VOLUNTEER", "CITIZEN"]
SHORT = {"ADMIN": "Admin", "DEVELOPER": "Dev", "COMMANDER": "Cmdr", "OPERATOR": "Oper", "RESCUE_OFFICER": "Officer",
         "VOLUNTEER": "Vol", "CITIZEN": "Citizen"}
GROUPS = [
    ("Public and self-service", ["incident.report", "incident.track", "public.read", "account.own", "alert.seen", "incident.view_own", "evidence.view_own"]),
    ("Incidents and evidence", ["incident.view_all", "incident.view_assigned", "incident.verify", "incident.progress", "incident.edit_risk",
                                "incident.reduce_risk", "incident.delete", "evidence.view_all", "evidence.view_assigned", "evidence.analyze"]),
    ("Supervisor, squads, dispatch", ["supervisor.view", "triage.run", "team.view", "team.manage", "dispatch.assign", "dispatch.approve", "beacon.view"]),
    ("Alerts", ["alert.publish", "alert.resolve", "alert.acknowledge_control"]),
    ("Resources and records", ["volunteer.view", "volunteer.verify", "volunteer.manage", "facility.manage", "record.view", "record.create", "record.export"]),
    ("Information", ["dashboard.view", "data.view", "vision.analyze"]),
    ("Administration and development", ["user.manage", "audit.read", "agency.view", "agency.manage", "system.diagnostics"]),
]
assert sorted(p for _, ps in GROUPS for p in ps) == sorted(ALL_PERMISSIONS), "a permission is missing from the document groups"

out = ["# Permission matrix (generated; do not edit by hand)",
       "",
       "Generated by `backend/scripts/generate_permission_matrix.py` from `backend/app/core/permissions.py` and "
       "`backend/tests/golden/endpoint_matrix.json`. Both are checked by tests, so this document cannot drift from the code.",
       "",
       "Symbols: ✔ allowed, – refused. Guests (not signed in) hold only `incident.report`, `incident.track` and `public.read`.",
       "Scope notes: `*.assigned` = only the officer's own team's missions; `*.own` = only the user's own records.",
       "",
       "## 1. Role × permission", ""]
header = "| Permission | " + " | ".join(SHORT[r] for r in ROLES) + " |"
sep = "|---|" + "---|" * len(ROLES)
for title, perms in GROUPS:
    out += [f"**{title}**", "", header, sep]
    for p in perms:
        out.append(f"| `{p}` | " + " | ".join("✔" if p in ROLE_PERMISSIONS[r] else "–" for r in ROLES) + " |")
    out.append("")

golden = json.loads((BACKEND / "tests" / "golden" / "endpoint_matrix.json").read_text())
cols = ["anonymous"] + ROLES
out += ["## 2. Endpoint × principal (observed by the test suite)", "",
        "401 = sign-in required, 403 = refused for that role, ✔ = reaches the handler (it may still return 404/409 for object-level rules).", "",
        "| Endpoint | Guest | " + " | ".join(SHORT[r] for r in ROLES) + " |", "|---|" + "---|" * (len(ROLES) + 1)]
for key in sorted(golden, key=lambda k: (k.split(" ", 1)[1], k.split(" ", 1)[0])):
    cells = [{"allow": "✔", "401": "401", "403": "403"}[golden[key][c]] for c in cols]
    out.append(f"| `{key}` | " + " | ".join(cells) + " |")
out.append("")
(BACKEND.parent / "docs" / "security" / "PERMISSION_MATRIX.md").write_text("\n".join(out))
print("written")
